import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { parseManifest } from "@scrollframe/core";
import { componentFor, type ComponentFile, type ProjectInfo } from "../src/index.js";

const base: ProjectInfo = {
  root: "/project",
  framework: "next",
  unsupported: null,
  router: "app",
  srcDir: false,
  typescript: true,
  packageManager: "pnpm",
  hasPackageJson: true,
  dependencies: [],
  publicDir: "public",
};
const ctx = (project: Partial<ProjectInfo>, extra: object = {}) => ({
  project: { ...base, ...project },
  name: "HeroSequence",
  video: "hero.mp4",
  out: "public/sequence",
  baseUrl: "/sequence",
  version: "0.2.0",
  ...extra,
});

const manifest = parseManifest({
  version: 1,
  frameCount: 60,
  baseUrl: "/sequence",
  pattern: "frame-{index}.webp",
  padding: 4,
  poster: "poster.webp",
  sets: [
    { name: "mobile", maxViewportWidth: 767, width: 320, height: 180, dir: "mobile" },
    { name: "desktop", maxViewportWidth: null, width: 960, height: 540, dir: "desktop" },
  ],
});
/** The file as written after the frames exist. */
const written = (file: ComponentFile | null) => file && { path: file.path, contents: file.render(manifest), usage: file.usage };

const REACT_TSX = `import { ScrollSequence } from "@scrollframe/react";
import manifest from "../public/sequence/manifest.json";

/** Scroll-driven sequence generated by scrollframe from hero.mp4. */
export default function HeroSequence() {
  return (
    <ScrollSequence manifest={manifest} alt="Describe the scene for search engines and screen readers" />
  );
}
`;

describe("componentFor: Next.js", () => {
  it("App Router + TypeScript: components/<Name>.tsx, used from app/page.tsx", () => {
    expect(written(componentFor("next", ctx({})))).toEqual({
      path: "components/HeroSequence.tsx",
      contents: REACT_TSX,
      usage: ["Render it in a page, e.g. app/page.tsx:", '  import HeroSequence from "../components/HeroSequence";', "  <HeroSequence />"],
    });
  });

  it("App Router under src/ + JavaScript: src/components/<Name>.jsx with a matching manifest path", () => {
    const file = written(componentFor("next", ctx({ srcDir: true, typescript: false })))!;
    expect(file.path).toBe("src/components/HeroSequence.jsx");
    expect(file.contents).toContain('import manifest from "../../public/sequence/manifest.json";');
    expect(file.usage[0]).toBe("Render it in a page, e.g. src/app/page.jsx:");
  });

  it("Pages Router: used from pages/index", () => {
    const file = componentFor("next", ctx({ router: "pages" }))!;
    expect(file.path).toBe("components/HeroSequence.tsx");
    expect(file.usage.slice(0, 2)).toEqual(["Render it in a page, e.g. pages/index.tsx:", '  import HeroSequence from "../components/HeroSequence";']);
  });
});

describe("componentFor: React", () => {
  it("Vite + TypeScript: src/components/<Name>.tsx, used from src/App.tsx", () => {
    expect(written(componentFor("react", ctx({ framework: "react", router: null, srcDir: true })))).toEqual({
      path: "src/components/HeroSequence.tsx",
      contents: REACT_TSX.replace("../public/", "../../public/"),
      usage: ["Render it in a component, e.g. src/App.tsx:", '  import HeroSequence from "./components/HeroSequence";', "  <HeroSequence />"],
    });
  });

  it("uses the frames folder and component name it is given", () => {
    const file = written(componentFor("react", ctx({ framework: "react", router: null, srcDir: true }, { name: "Intro", out: "public/media/intro" })))!;
    expect(file.path).toBe("src/components/Intro.tsx");
    expect(file.contents).toContain('import manifest from "../../public/media/intro/manifest.json";');
    expect(file.contents).toContain("export default function Intro() {");
  });
});

describe("componentFor: plain HTML", () => {
  it("writes a snippet with the CDN lines and the server-rendered poster, for the CLI's minor version", () => {
    const file = written(componentFor("html", ctx({ framework: "html", hasPackageJson: false }, { out: "sequence", version: "0.3.1" })))!;
    expect(file.path).toBe("hero-sequence.html");
    expect(file.contents).toContain('<link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/@scrollframe/element@0.3/dist/scroll-sequence.css" />');
    expect(file.contents).toContain('<script src="https://cdn.jsdelivr.net/npm/@scrollframe/element@0.3" defer></script>');
    expect(file.contents).toContain(
      '<scroll-sequence src="/sequence/manifest.json" alt="Describe the scene for search engines and screen readers">',
    );
    expect(file.contents).toContain('<div data-sf-stage="" style="position:sticky;top:0;height:100svh;overflow:hidden"><picture>');
    expect(file.contents).toContain('src="/sequence/desktop/poster.webp"');
    expect(file.usage).toEqual([
      "Paste the two <head> lines and the <scroll-sequence> block from hero-sequence.html into your page.",
    ]);
  });
});

describe("componentFor: Angular", () => {
  it("writes a standalone component that loads the frames from src, and says where to import it", () => {
    const file = written(componentFor("angular", ctx({ framework: "angular", router: null, srcDir: true })))!;
    expect(file).toEqual({
      path: "src/app/hero-sequence/hero-sequence.ts",
      contents: `import { CUSTOM_ELEMENTS_SCHEMA, Component } from "@angular/core";
import "@scrollframe/element";

/** Scroll-driven sequence generated by scrollframe from hero.mp4. */
@Component({
  selector: "app-hero-sequence",
  schemas: [CUSTOM_ELEMENTS_SCHEMA],
  template: \`
    <scroll-sequence src="/sequence/manifest.json" alt="Describe the scene for search engines and screen readers">
    </scroll-sequence>
  \`,
})
export class HeroSequence {}
`,
      usage: [
        "Add it to a component, e.g. src/app/app.ts:",
        '  import { HeroSequence } from "./hero-sequence/hero-sequence";',
        "  imports: [HeroSequence],  and in its template:  <app-hero-sequence />",
      ],
    });
  });
});

describe("componentFor: Vue", () => {
  const VUE_CONFIG_LINE =
    '  vue({ template: { compilerOptions: { isCustomElement: (tag) => tag === "scroll-sequence" } } })';

  it("writes a TypeScript SFC that loads the frames from src, and prints the vite.config line", () => {
    const file = written(componentFor("vue", ctx({ framework: "vue", router: null, srcDir: true, root: "/nonexistent" })))!;
    expect(file).toEqual({
      path: "src/components/HeroSequence.vue",
      contents: `<script setup lang="ts">
// Scroll-driven sequence generated by scrollframe from hero.mp4.
import "@scrollframe/element";
import "@scrollframe/element/style.css";
</script>

<template>
  <scroll-sequence src="/sequence/manifest.json" alt="Describe the scene for search engines and screen readers">
  </scroll-sequence>
</template>
`,
      usage: [
        "Render it in a component, e.g. src/App.vue:",
        '  import HeroSequence from "./components/HeroSequence.vue";',
        "  <HeroSequence />",
        "",
        "Tell Vue that <scroll-sequence> is a custom element, in vite.config:",
        VUE_CONFIG_LINE,
      ],
    });
  });

  it("uses plain <script setup> without TypeScript", () => {
    const file = written(componentFor("vue", ctx({ framework: "vue", router: null, srcDir: true, typescript: false, root: "/nonexistent" })))!;
    expect(file.contents.startsWith("<script setup>\n")).toBe(true);
  });

  it("does not print the vite.config line when it is already configured", () => {
    const root = mkdtempSync(join(tmpdir(), "scrollframe-vue-"));
    writeFileSync(join(root, "vite.config.ts"), `export default { plugins: [vue({ template: { compilerOptions: { isCustomElement: (t) => t === "scroll-sequence" } } })] };`);
    const file = written(componentFor("vue", ctx({ framework: "vue", router: null, srcDir: true, root })))!;
    expect(file.usage).toEqual([
      "Render it in a component, e.g. src/App.vue:",
      '  import HeroSequence from "./components/HeroSequence.vue";',
      "  <HeroSequence />",
    ]);
    rmSync(root, { recursive: true, force: true });
  });
});

describe("componentFor: untrusted video names", () => {
  it("cannot close the comment it is written in", () => {
    for (const framework of ["next", "angular", "vue", "html"] as const) {
      const file = written(componentFor(framework, ctx({ framework, router: framework === "next" ? "app" : null, srcDir: true, root: "/nonexistent" }, { video: "evil --> <script>\n*.mp4" })))!;
      // A file name cannot contain "/", so "*/" cannot appear; "-->", "<", "*" and line breaks can.
      expect(file.contents).toContain("evil --_ _script___.mp4");
      expect(file.contents).not.toContain("-->  <");
    }
  });
});

describe("componentFor: what every template shares", () => {
  const all = ["next", "react", "angular", "vue", "html"] as const;

  it.each(all)("%s writes no heading over the video", (framework) => {
    const file = written(componentFor(framework, ctx({ framework })))!;
    expect(file.contents).not.toMatch(/<h1|headline/i);
  });

  it.each(["angular", "vue", "html"] as const)("%s takes the scroll length of the sequence before any script runs", (framework) => {
    const file = componentFor(framework, ctx({ framework }))!;
    expect(file.render({ ...manifest, scrollLength: "630vh" })).toContain('scroll-length="630vh" style="--sf-scroll-length:630vh"');
    expect(file.render(manifest)).not.toContain("scroll-length");
  });
});
