import { basename, join, posix } from "node:path";
import { renderStageMarkup, type SequenceManifest } from "@scrollframe/core";
import type { Framework, ProjectInfo } from "./detect.js";
import { readText } from "./files.js";

/** A component file the CLI writes into the user's project. */
export interface ComponentFile {
  /** Relative to the project root, with forward slashes. */
  path: string;
  /** The file contents, rendered once the frames (and their manifest) exist. */
  render(manifest: SequenceManifest): string;
  /** Lines printed at the end: how to use the component. */
  usage: string[];
}

export interface TemplateContext {
  project: ProjectInfo;
  /** PascalCase component name, also the file name. */
  name: string;
  /** The source video, named in the generated file. */
  video: string;
  /** Output folder of the frames, relative to the project root (e.g. `public/sequence`). */
  out: string;
  /** Public URL of that folder (e.g. `/sequence`). */
  baseUrl: string;
  /** Version of this CLI; the packages are released together, so it picks the CDN version. */
  version: string;
}

const ALT = "Describe the scene for search engines and screen readers";

/** The video's file name, safe inside a JS or HTML comment: no comment terminators or line breaks. */
const commentSafe = (video: string) => basename(video).replace(/[^A-Za-z0-9 ._()\/-]/g, "_");

const toPosix = (path: string) => path.replace(/\\/g, "/").replace(/\/+$/, "");

/** Import specifier from the file at `from` to the file at `to`, both relative to the root. */
function importPath(from: string, to: string): string {
  const relative = posix.relative(posix.dirname(from), to);
  return relative.startsWith(".") ? relative : `./${relative}`;
}

function reactComponent(context: TemplateContext, page: string): ComponentFile {
  const { project, name, video, out } = context;
  const ext = project.typescript ? "tsx" : "jsx";
  const src = project.srcDir ? "src/" : "";
  const path = `${src}components/${name}.${ext}`;
  const manifest = importPath(path, `${toPosix(out)}/manifest.json`);
  const pagePath = `${src}${page}.${ext}`;
  return {
    path,
    render: () => `import { ScrollSequence } from "@scrollframe/react";
import manifest from "${manifest}";

/** Scroll-driven sequence generated by scrollframe from ${commentSafe(video)}. */
export default function ${name}() {
  return (
    <ScrollSequence manifest={manifest} alt="${ALT}">
      <h1>Your headline</h1>
    </ScrollSequence>
  );
}
`,
    usage: [
      `Render it in a ${page === "App" ? "component" : "page"}, e.g. ${pagePath}:`,
      `  import ${name} from "${importPath(pagePath, `${src}components/${name}`)}";`,
      `  <${name} />`,
    ],
  };
}

const kebab = (name: string) => name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

/** A snippet to paste into any HTML page: CDN lines plus the poster rendered as HTML (best LCP). */
function htmlSnippet(context: TemplateContext): ComponentFile {
  const path = `${kebab(context.name)}.html`;
  const cdn = `https://cdn.jsdelivr.net/npm/@scrollframe/element@${context.version.split(".").slice(0, 2).join(".")}`;
  return {
    path,
    render: (manifest) => `<!-- scrollframe: generated from ${commentSafe(context.video)}. Paste it into your page. -->

<!-- 1. In <head>: -->
<link rel="stylesheet" href="${cdn}/dist/scroll-sequence.css" />
<script src="${cdn}" defer></script>

<!-- 2. Where the sequence goes (the poster is already in the HTML, so it shows before any script runs): -->
<scroll-sequence src="${context.baseUrl}/manifest.json" alt="${ALT}">
  ${renderStageMarkup(manifest, { alt: ALT })}
  <h1>Your headline</h1>
</scroll-sequence>
`,
    usage: [`Paste the two <head> lines and the <scroll-sequence> block from ${path} into your page.`],
  };
}

/** A standalone Angular component; Angular serves public/ at the site root, so the frames load from `src`. */
function angularComponent(context: TemplateContext): ComponentFile {
  const { name, video, baseUrl } = context;
  const file = kebab(name);
  const path = `src/app/${file}/${file}.ts`;
  return {
    path,
    render: () => `import { CUSTOM_ELEMENTS_SCHEMA, Component } from "@angular/core";
import "@scrollframe/element";

/** Scroll-driven sequence generated by scrollframe from ${commentSafe(video)}. */
@Component({
  selector: "app-${file}",
  schemas: [CUSTOM_ELEMENTS_SCHEMA],
  template: \`
    <scroll-sequence src="${baseUrl}/manifest.json" alt="${ALT}">
      <h1>Your headline</h1>
    </scroll-sequence>
  \`,
})
export class ${name} {}
`,
    usage: [
      "Add it to a component, e.g. src/app/app.ts:",
      `  import { ${name} } from "./${file}/${file}";`,
      `  imports: [${name}],  and in its template:  <app-${file} />`,
    ],
  };
}

const VITE_CONFIGS = ["vite.config.ts", "vite.config.js", "vite.config.mjs", "vite.config.mts"];

/** The project's vite.config already declares <scroll-sequence> as a custom element. */
function viteKnowsElement(root: string): boolean {
  return VITE_CONFIGS.some((file) => {
    const config = readText(join(root, file)) ?? "";
    return config.includes("isCustomElement") && config.includes("scroll-sequence");
  });
}

/** A Vue SFC. vite.config is code, so the CLI prints the line to add instead of editing it. */
function vueComponent(context: TemplateContext): ComponentFile {
  const { project, name, video, baseUrl } = context;
  const path = `src/components/${name}.vue`;
  const usage = [
    "Render it in a component, e.g. src/App.vue:",
    `  import ${name} from "./components/${name}.vue";`,
    `  <${name} />`,
  ];
  if (!viteKnowsElement(project.root)) {
    usage.push(
      "",
      "Tell Vue that <scroll-sequence> is a custom element, in vite.config:",
      '  vue({ template: { compilerOptions: { isCustomElement: (tag) => tag === "scroll-sequence" } } })',
    );
  }
  return {
    path,
    render: () => `<script setup${project.typescript ? ' lang="ts"' : ""}>
// Scroll-driven sequence generated by scrollframe from ${commentSafe(video)}.
import "@scrollframe/element";
import "@scrollframe/element/style.css";
</script>

<template>
  <scroll-sequence src="${baseUrl}/manifest.json" alt="${ALT}">
    <h1>Your headline</h1>
  </scroll-sequence>
</template>
`,
    usage,
  };
}

/** The component for `framework`, or null when there is no template for it yet. */
export function componentFor(framework: Framework, context: TemplateContext): ComponentFile | null {
  switch (framework) {
    case "next":
      return reactComponent(context, context.project.router === "pages" ? "pages/index" : "app/page");
    case "react":
      return reactComponent(context, "App");
    case "angular":
      return angularComponent(context);
    case "vue":
      return vueComponent(context);
    case "html":
      return htmlSnippet(context);
    default:
      return null;
  }
}
